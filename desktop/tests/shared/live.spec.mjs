// 真实站点验收：用户仅在窗口登录；不保存登录 trace、截图、Cookie 或设备令牌。
import { test, expect, _electron } from '@playwright/test'
import { mkdtemp, mkdir, rm, writeFile, readdir, readFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'

test('真实站点：里程碑、生产依赖、甘特筛选和包内 Runner', async ({}, info) => {
  const profile = await mkdtemp(path.join(tmpdir(), 'mycollab-live-acceptance-'))
  const prefix = `Windows自动验收-${Date.now()}`
  const records = { prefix, cases: [], data: {}, scope: '真实安装版与用户指定 HTTPS 站点；无模型调用；未保存 trace 或截图。' }
  const app = await _electron.launch({ executablePath: process.env.MYCOLLAB_TEST_APP_BINARY,
    args: [`--user-data-dir=${profile}`], timeout: 20000 })
  const page = await app.firstWindow()
  page.setDefaultTimeout(15000)
  const get = async url => page.evaluate(async url => {
    const response = await fetch(url)
    if (!response.ok) throw new Error(`读取验收数据失败：HTTP ${response.status}`)
    return response.json()
  }, url)
  const visit = async route => page.goto(`mycollab://app${route}`)
  const record = async (name, action) => {
    try { await test.step(name, action); records.cases.push({ name, result: '通过' }) }
    catch (error) { records.cases.push({ name, result: '失败', error: error.message }); console.log(`验收项失败：${name}`) }
    await writeFile(info.outputPath('acceptance.json'), JSON.stringify(records, null, 2))
  }
  const confirm = async () => page.getByRole('dialog', { name: '变更状态', exact: true }).getByRole('button', { name: /^(OK|确定)$/ }).click()
  const completeMission = async id => {
    await visit(`/missions/${id}`)
    await page.getByRole('button', { name: '认领', exact: true }).click()
    await page.getByRole('button', { name: '提交成果', exact: true }).click()
    const form = page.getByRole('dialog', { name: '提交成果', exact: true })
    await form.getByPlaceholder('成果说明、测试结果或链接（支持 Markdown）').fill('自动验收专用任务，无生产成果。')
    await form.locator('textarea').nth(1).fill('自动检查页面与服务端状态一致。')
    await form.getByRole('button', { name: '提交', exact: true }).click()
    await expect(form).not.toBeVisible()
    await page.getByRole('button', { name: '验收', exact: true }).click()
    const review = page.getByRole('dialog', { name: '验收通过', exact: true })
    await review.getByRole('textbox', { name: '验收说明（无构建时必填）', exact: true }).fill('自动验收测试数据，状态检查通过。')
    await review.getByRole('button', { name: '确认通过', exact: true }).click()
    await expect(review).not.toBeVisible()
    await page.reload()
    expect((await get(`/api/missions/${id}/`)).status).toBe('Done')
  }
  try {
    await mkdir(info.outputDir, { recursive: true })
    expect(await app.evaluate(({ app }) => app.getPath('userData'))).toBe(profile)
    await page.getByPlaceholder('https://collab.example.com').fill(process.env.MYCOLLAB_ACCEPTANCE_SERVER)
    await page.getByRole('button', { name: '保存服务器并前往登录' }).click()
    await expect(page).toHaveURL(/\/login/)
    await app.evaluate(({ BrowserWindow }) => { const win = BrowserWindow.getAllWindows()[0]; win.setTitle('MyCollab 自动验收：请登录专用测试账号'); win.show(); win.focus() })
    console.log('等待用户在独立验收窗口登录，最长 5 分钟；不会记录密码。')
    await page.waitForURL(/\/my-work(?:\?|$)/, { timeout: 300000 })
    console.log('登录完成，开始自动验收。')

    await record('创建里程碑并切换为进行中', async () => {
      await visit('/milestones')
      await page.getByRole('button', { name: '新建里程碑', exact: true }).click()
      const form = page.getByRole('dialog', { name: '新建里程碑', exact: true })
      await form.getByLabel('名称', { exact: true }).fill(prefix)
      await form.getByLabel('目标说明', { exact: true }).fill('自动验收专用：生产任务、依赖与里程碑完成规则。')
      await form.getByRole('button', { name: '创建', exact: true }).click()
      await expect(form).not.toBeVisible()
      await page.getByRole('link', { name: prefix, exact: true }).click()
      await expect(page).toHaveURL(/\/milestones\/[^/?]+$/)
      records.data.milestone = page.url().split('/').at(-1)
      expect((await get(`/api/milestones/${records.data.milestone}/`)).status).toBe('Planned')
      await page.getByRole('button', { name: '开始', exact: true }).click(); await confirm()
      await expect.poll(async () => (await get(`/api/milestones/${records.data.milestone}/`)).status).toBe('Active')
      await page.reload()
      await expect(page.getByRole('heading', { name: prefix, exact: true })).toBeVisible()
    })

    await record('两步生产模板创建与刷新', async () => {
      await visit('/design/templates')
      await page.getByRole('button', { name: '新建模板', exact: true }).click()
      const form = page.getByRole('dialog', { name: '新建生产模板', exact: true })
      await form.getByLabel('名称', { exact: true }).fill(prefix)
      await form.getByLabel('说明', { exact: true }).fill('自动验收专用两步依赖模板。')
      await form.getByRole('button', { name: '添加步骤（1/30）', exact: true }).click()
      for (let i = 0; i < 2; i++) {
        const card = form.locator('.step-card').nth(i)
        await card.getByLabel('步骤标题', { exact: true }).fill(`步骤${i + 1}`)
        await card.getByLabel('背景与目标', { exact: true }).fill('自动验收测试步骤。')
        await card.getByLabel('验收标准', { exact: true }).fill('状态与依赖正确。')
      }
      await form.locator('.step-card').nth(1).getByLabel('前置步骤', { exact: true }).press('Enter')
      await page.getByRole('option', { name: '步骤1（step_1）', exact: true }).click()
      await form.getByLabel('名称', { exact: true }).click()
      await form.getByRole('button', { name: '保存模板', exact: true }).click()
      await expect(form).not.toBeVisible()
      const list = await get(`/api/production-templates/?q=${encodeURIComponent(prefix)}`)
      const template = list.results.find(item => item.name === prefix)
      expect(template.steps[1].prerequisite_keys).toEqual(['step_1'])
      records.data.template = template.id
      await page.reload()
      await expect(page.getByRole('button', { name: prefix, exact: true })).toBeVisible()
    })

    await record('资产实例化两步任务，关联里程碑并保留依赖', async () => {
      expect(Boolean(records.data.template && records.data.milestone), '前置验收未完成').toBe(true)
      await visit('/design')
      await page.getByRole('button', { name: '新建条目', exact: true }).click()
      const form = page.getByRole('dialog', { name: '新建设计条目', exact: true })
      await form.getByLabel('标题', { exact: true }).fill(prefix)
      await form.getByLabel('类型', { exact: true }).press('Enter')
      await page.getByRole('option', { name: '资产', exact: true }).click()
      await form.getByLabel('设计内容', { exact: true }).fill('自动验收专用资产。')
      await form.getByRole('button', { name: '保存', exact: true }).click()
      await expect(form).not.toBeVisible()
      // 搜索避免依赖首屏树分页位置；写入仍由真实表单完成。
      await page.getByPlaceholder('搜索设计或资产的标题与正文').fill(prefix)
      await page.getByPlaceholder('搜索设计或资产的标题与正文').press('Enter')
      await page.getByRole('link', { name: prefix, exact: true }).click()
      records.data.asset = page.url().split('/').at(-1)
      await page.locator('.el-select').filter({ hasText: '选择生产模板' }).getByRole('combobox').fill(prefix)
      await page.getByRole('option', { name: `${prefix}（2 步）`, exact: true }).click()
      await page.locator('.el-select').filter({ hasText: '可选目标里程碑' }).getByRole('combobox').press('Enter')
      await page.getByRole('option', { name: prefix, exact: true }).click()
      await page.getByRole('button', { name: '预览生产步骤', exact: true }).click()
      const preview = page.getByRole('dialog', { name: '确认生成生产任务', exact: true })
      await preview.getByRole('button', { name: '生成 2 个待认领 Mission', exact: true }).click()
      await expect(preview).not.toBeVisible()
      await page.reload()
      const production = await get(`/api/design-elements/${records.data.asset}/production/`)
      expect(production.items).toHaveLength(2)
      records.data.missions = production.items.map(item => item.mission.id)
      const [first, second] = await Promise.all(records.data.missions.map(id => get(`/api/missions/${id}/`)))
      expect(first.status).toBe('Open'); expect(second.status).toBe('Open')
      expect(second.prerequisites.map(item => item.id)).toContain(first.id)
      expect(second.is_blocked).toBe(true)
      expect(first.milestone.id).toBe(records.data.milestone)
      await expect(page.getByRole('button', { name: '预览生产步骤', exact: true })).toHaveCount(0)
    })

    await record('依次完成生产任务，里程碑仅手动完成', async () => {
      expect(records.data.missions?.length, '前置实例化未完成').toBe(2)
      await completeMission(records.data.missions[0])
      expect((await get(`/api/missions/${records.data.missions[1]}/`)).is_blocked).toBe(false)
      await completeMission(records.data.missions[1])
      await visit(`/milestones/${records.data.milestone}`)
      expect((await get(`/api/milestones/${records.data.milestone}/`)).status).toBe('Active')
      await page.getByRole('button', { name: '完成', exact: true }).click(); await confirm()
      await expect.poll(async () => (await get(`/api/milestones/${records.data.milestone}/`)).status).toBe('Completed')
      await page.reload()
      await expect(page.getByText('已完成', { exact: true }).first()).toBeVisible()
    })

    await record('甘特个人筛选保存并刷新恢复', async () => {
      await visit('/workspace')
      await page.getByRole('radio', { name: '甘特图', exact: true }).check()
      await page.getByRole('button', { name: '保存当前筛选', exact: true }).click()
      const form = page.getByRole('dialog', { name: '保存筛选', exact: true })
      await form.getByLabel('名称', { exact: true }).fill(prefix)
      await form.getByRole('button', { name: '确认保存', exact: true }).click()
      await expect(form).not.toBeVisible()
      await expect(page).toHaveURL(/saved_view=/)
      records.data.savedView = new URL(page.url()).searchParams.get('saved_view')
      await page.reload()
      await expect(page.getByRole('radio', { name: '甘特图', exact: true })).toBeChecked()
      await expect(page.getByText(`${prefix} · 个人`, { exact: true })).toBeVisible()
    })

    await record('包内 Runner 绑定、自检、启停与隐藏恢复', async () => {
      await visit('/agent-devices')
      await page.getByRole('textbox', { name: '设备名称', exact: true }).fill(prefix)
      await page.getByRole('button', { name: '创建设备凭据', exact: true }).click()
      await expect(page.getByRole('textbox', { name: '设备凭据', exact: true })).toBeVisible()
      // 令牌只在内存中用于布尔比较，不输出到报告。
      const token = await page.getByRole('textbox', { name: '设备凭据', exact: true }).inputValue()
      records.data.device = (await get('/api/agent-devices/?page_size=100')).results.find(item => item.name === prefix).id
      await page.getByPlaceholder('provider/model').fill('test/no-provider')
      await page.getByRole('textbox', { name: 'OpenCode 可执行文件', exact: true }).fill(path.join(profile, 'missing-opencode.exe'))
      await page.getByRole('button', { name: '验证并加密保存到本机', exact: true }).click()
      await expect(page.getByRole('button', { name: '启动 Runner', exact: true })).toBeEnabled({ timeout: 20000 })
      const files = (await readdir(path.join(profile, 'devices'))).filter(name => name.endsWith('.encrypted'))
      expect(files.length).toBe(1)
      expect((await readFile(path.join(profile, 'devices', files[0]))).includes(Buffer.from(token))).toBe(false)
      await page.reload()
      await expect(page.getByPlaceholder('provider/model')).toHaveValue('test/no-provider')
      await expect(page.getByRole('textbox', { name: '设备令牌', exact: true })).toHaveValue('')
      await page.getByRole('button', { name: '自检（不调用模型）', exact: true }).click()
      await expect(page.getByText('找不到可执行文件，请核对完整路径。', { exact: true })).toBeVisible({ timeout: 20000 })
      await page.getByRole('button', { name: '启动 Runner', exact: true }).click()
      await expect(page.getByText('等待任务', { exact: true })).toBeVisible({ timeout: 20000 })
      await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].close())
      await expect.poll(() => app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isVisible())).toBe(false)
      await app.evaluate(({ app }) => app.emit('activate'))
      await expect(page.getByText('等待任务', { exact: true })).toBeVisible()
      await page.getByRole('button', { name: '停止 Runner', exact: true }).click()
      await expect(page.getByText('已停止', { exact: true })).toBeVisible({ timeout: 20000 })
      await page.getByRole('button', { name: '启动 Runner', exact: true }).click()
      await expect(page.getByText('等待任务', { exact: true })).toBeVisible({ timeout: 20000 })
      await page.getByRole('button', { name: '退出', exact: true }).click()
      await expect(page).toHaveURL(/\/login/)
      expect((await page.evaluate(() => window.mycollabDesktop.runnerStatus())).state).toBe('stopped')
    })
    expect(records.cases.filter(item => item.result === '失败').map(item => item.name)).toEqual([])
  } finally {
    await writeFile(info.outputPath('acceptance.json'), JSON.stringify(records, null, 2))
    await app.close()
    await rm(profile, { recursive: true, force: true, maxRetries: 5, retryDelay: 300 })
  }
})
